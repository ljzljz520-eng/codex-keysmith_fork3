def test_component_coverage_npm_cargo_pypi(tmp_path):
    repo = make_repo(tmp_path)
    spdx_document, cdx_document, _ = build(repo)
    purls = {component.get("purl") for component in cdx_libraries(cdx_document)}
    assert "pkg:npm/left-pad@1.3.0" in purls
    assert "pkg:npm/string-width@4.2.3" in purls
    # Nested duplicate version from the real lock layout is retained.
    assert "pkg:npm/string-width@7.2.0" in purls
    assert "pkg:cargo/adler2@2.0.1" in purls
    assert "pkg:pypi/pyinstaller@6.16.0" in purls

    left_pad = find_library(cdx_document, "left-pad")
    assert left_pad["hashes"][0]["alg"] == "SHA-512"
    assert left_pad["hashes"][0]["content"] == ("01" * 64)
    adler = find_library(cdx_document, "adler2")
    assert adler["hashes"][0] == {
        "alg": "SHA-256",
        "content": "320119579fcad9c21884f5c4861d16174d0e06250625266f50fe6898340abefa",
    }
    # The local (path) crate is inventoried without a registry purl.
    memchr = find_library(cdx_document, "memchr", version="2.7.4")
    assert "purl" not in memchr and not memchr.get("hashes")
    # Dev-only npm packages are marked optional.
    no_integrity = find_library(cdx_document, "nointegrity")
    assert no_integrity["scope"] == "optional"
    assert not no_integrity.get("hashes")

    spdx_packages = {pkg["name"]: pkg for pkg in spdx_document["packages"]}
    assert "npm:left-pad" in spdx_packages
    assert spdx_packages["cargo:adler2"]["checksums"][0]["algorithm"] == "SHA256"
    spdx_files = {entry["fileName"]: entry for entry in spdx_document["files"]}
    assert "./codex-instruct.py" in spdx_files
    assert "./gui/requirements-build.txt" in spdx_files


def test_cargo_dependency_edges_are_recorded(tmp_path):
    repo = make_repo(tmp_path)
    _, cdx_document, _ = build(repo)
    adler = find_library(cdx_document, "adler2")
    memchr = find_library(cdx_document, "memchr", version="2.7.4")
    edges = {dep["ref"]: dep["dependsOn"] for dep in cdx_document["dependencies"]}
    assert memchr["bom-ref"] in edges[adler["bom-ref"]]
    spdx_document, _, _ = build(repo)
    assert any(
        rel["relationshipType"] == "DEPENDS_ON"
        and rel["relatedSpdxElement"] == memchr["bom-ref"]
        and rel["spdxElementId"] == adler["bom-ref"]
        for rel in spdx_document["relationships"]
    )


def test_tampered_lock_files_change_or_fail(tmp_path):
    repo = make_repo(tmp_path)
    _, baseline_cdx, _ = build(repo)
    baseline = sbom.render_document(baseline_cdx)

    # A changed cargo checksum changes the component hash and the document.
    changed_lock = CARGO_LOCK.replace(
        "320119579fcad9c21884f5c4861d16174d0e06250625266f50fe6898340abefa",
        "420119579fcad9c21884f5c4861d16174d0e06250625266f50fe6898340abefa",
    )
    repo_b = make_repo(tmp_path / "b", cargo_lock=changed_lock)
    _, changed_cdx, _ = build(repo_b)
    assert sbom.render_document(changed_cdx) != baseline
    assert find_library(changed_cdx, "adler2")["hashes"][0]["content"].startswith("4201")

    tampered_npm = json.loads(json.dumps(NPM_LOCK))
    tampered_npm["packages"]["node_modules/left-pad"]["version"] = "9.9.9"
    repo_c = make_repo(tmp_path / "c", npm_lock=tampered_npm)
    _, cdx_c, _ = build(repo_c)
    assert "pkg:npm/left-pad@9.9.9" in {c.get("purl") for c in cdx_libraries(cdx_c)}


def test_malformed_lock_inputs_fail_closed(tmp_path):
    def expect_error(repo_kwargs=None, *, pip_pins=None, cargo_lock=None,
                     npm_document=None):
        repo = tmp_path / ("bad-" + str(len(list(tmp_path.iterdir()))))
        kwargs = {}
        if pip_pins is not None:
            kwargs["pip_pins"] = pip_pins
        if cargo_lock is not None:
            kwargs["cargo_lock"] = cargo_lock
        make_repo(repo, npm_lock=npm_document, **kwargs)
        with pytest.raises(sbom.SbomError):
            build(repo, fixed_files=FIXED_FILES)

    bad_integrity = json.loads(json.dumps(NPM_LOCK))
    bad_integrity["packages"]["node_modules/left-pad"]["integrity"] = "sha1-AAAA"
    expect_error(npm_document=bad_integrity)

    short_integrity = json.loads(json.dumps(NPM_LOCK))
    short_integrity["packages"]["node_modules/left-pad"]["integrity"] = (
        "sha512-" + base64.b64encode(b"\x00" * 32).decode())
    expect_error(npm_document=short_integrity)

    missing_version = json.loads(json.dumps(NPM_LOCK))
    del missing_version["packages"]["node_modules/left-pad"]["version"]
    expect_error(npm_document=missing_version)

    bad_lock_version = json.loads(json.dumps(NPM_LOCK))
    bad_lock_version["lockfileVersion"] = 2
    expect_error(npm_document=bad_lock_version)

    expect_error(cargo_lock="# generated\nversion = 4\nname = \"x\"\n")
    expect_error(cargo_lock=CARGO_LOCK.replace(
        'checksum = "3201', 'checksum = "zzzz'))
    expect_error(pip_pins="PyInstaller>=6.0\n")
    expect_error(pip_pins="https://example.local/PyInstaller.whl\n")


def test_partial_desktop_inputs_fail_but_desktop_optional(tmp_path):
    repo = make_repo(tmp_path / "full")
    spdx_document, cdx_document, _ = build(repo)
    assert cdx_libraries(cdx_document)

    partial = tmp_path / "partial"
    make_repo(partial)
    shutil.rmtree(partial / "gui" / "src-tauri")
    with pytest.raises(sbom.SbomError):
        build(partial, fixed_files=FIXED_FILES)

    no_gui = tmp_path / "nogui"
    make_repo(no_gui, with_desktop=False)
    spdx_document, cdx_document, records = build(no_gui, fixed_files=FIXED_FILES)
    assert not cdx_libraries(cdx_document)
    assert "./gui/package-lock.json" not in {
        entry["fileName"] for entry in spdx_document["files"]
    }
    assert records


