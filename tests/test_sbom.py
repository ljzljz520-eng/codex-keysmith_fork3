def test_dual_documents_have_required_schema_fields(tmp_path):
    repo = make_repo(tmp_path)
    spdx_document, cdx_document, records = build(repo)
    assert spdx_document["spdxVersion"] == "SPDX-2.3"
    assert spdx_document["dataLicense"] == "CC0-1.0"
    assert spdx_document["documentDescribes"] == ["SPDXRef-Package-" + sbom.PRODUCT]
    assert spdx_document["creationInfo"]["created"] == ISSUED_AT
    assert "codex-keysmith" in spdx_document["documentNamespace"]
    assert spdx_document["files"], "SPDX document must inventory files"
    assert len(spdx_document["packages"]) >= 2
    relationship_types = {
        (rel["spdxElementId"], rel["relationshipType"]) for rel in spdx_document["relationships"]
    }
    assert ("SPDXRef-DOCUMENT", "DESCRIBES") in relationship_types
    assert any(kind == "CONTAINS" for _, kind in relationship_types)
    assert any(kind == "DEPENDS_ON" for _, kind in relationship_types)

    assert cdx_document["bomFormat"] == "CycloneDX"
    assert cdx_document["specVersion"] == "1.6"
    assert cdx_document["serialNumber"].startswith("urn:uuid:")
    assert cdx_document["version"] == 1
    assert cdx_document["metadata"]["timestamp"] == ISSUED_AT
    assert cdx_document["metadata"]["component"]["version"] == "0.6.0"
    assert cdx_document["dependencies"], "CDX document must declare dependencies"
    product_deps = next(
        dep for dep in cdx_document["dependencies"]
        if dep["ref"] == "SPDXRef-Package-" + sbom.PRODUCT
    )
    assert product_deps["dependsOn"], "product must depend on files/components"

    for entry in spdx_document["files"]:
        assert len(entry["checksums"]) == 1
        checksum = entry["checksums"][0]
        assert checksum["algorithm"] == "SHA256" and len(checksum["checksumValue"]) == 64
    expected_hash_length = {"SHA-256": 64, "SHA-512": 128}
    for component in cdx_document["components"]:
        assert component["bom-ref"]
        for checksum in component.get("hashes", []):
            assert checksum["alg"] in expected_hash_length
            assert len(checksum["content"]) == expected_hash_length[checksum["alg"]]
    # Every inventoried file appears in both documents.
    assert len(cdx_files(cdx_document)) == len(spdx_document["files"]) == len(records)


def test_documents_byte_identical_across_runs(tmp_path):
    repo = make_repo(tmp_path)
    spdx_a, cdx_a, records_a = build(repo)
    spdx_b, cdx_b, records_b = build(repo)
    assert sbom.render_document(spdx_a) == sbom.render_document(spdx_b)
    assert sbom.render_document(cdx_a) == sbom.render_document(cdx_b)
    assert records_a == records_b
    json.loads(sbom.render_document(spdx_a))
    json.loads(sbom.render_document(cdx_a))


def test_documents_change_with_inputs_but_not_arg_order(tmp_path):
    repo = make_repo(tmp_path)
    spdx_a, cdx_a, _ = build(repo)
    spdx_b, cdx_b, _ = build(repo, source_commit=("f" * 40))
    assert sbom.render_document(spdx_a) != sbom.render_document(spdx_b)
    assert sbom.render_document(cdx_a) != sbom.render_document(cdx_b)
    # Deterministic serial number is tag+line+commit bound.
    assert cdx_a["serialNumber"] != cdx_b["serialNumber"]


def test_written_assets_are_deterministic_and_self_describing(tmp_path):
    repo = make_repo(tmp_path)
    spdx_document, cdx_document, _ = build(repo)
    out_dir = tmp_path / "dist"
    records = sbom.write_sbom_documents(spdx_document, cdx_document,
                                        out_dir=out_dir, tag="v0.6.0")
    spdx_name, cdx_name = sbom.sbom_asset_names("v0.6.0")
    assert set(records) == {spdx_name, cdx_name}
    for name, record in records.items():
        data = (out_dir / name).read_bytes()
        assert hashlib.sha256(data).hexdigest() == record["sha256"]
        assert len(data) == record["size"]
    # Rewriting is byte-for-byte stable.
    again = sbom.write_sbom_documents(spdx_document, cdx_document,
                                      out_dir=out_dir, tag="v0.6.0")
    assert again == records
    assert (out_dir / spdx_name).read_bytes() == sbom.render_document(spdx_document)


def test_file_records_are_recomputable_sha256(tmp_path):
    repo = make_repo(tmp_path)
    _, _, records = build(repo)
    for relative, (digest_hex, size) in records.items():
        data = (repo / relative).read_bytes()
        assert hashlib.sha256(data).hexdigest() == digest_hex
        assert len(data) == size


