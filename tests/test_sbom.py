def test_cli_writes_documents_and_reports_records(tmp_path, capsys):
    repo = make_repo(tmp_path / "repo")
    out_dir = tmp_path / "out"
    argv = [
        "--repo-root", str(repo), "--release-line", "stable", "--version", "0.6.0",
        "--issued-at", ISSUED_AT, "--commit", COMMIT, "--out-dir", str(out_dir),
    ]
    for name in FIXED_FILES:
        argv.extend(("--fixed-file", name))
    exit_code = sbom.main(argv)
    assert exit_code == 0
    report = json.loads(capsys.readouterr().out)
    spdx_name, cdx_name = sbom.sbom_asset_names("v0.6.0")
    assert set(report) == {spdx_name, cdx_name}
    assert (out_dir / spdx_name).is_file()

    bad_argv = [
        "--repo-root", str(repo), "--release-line", "stable", "--version", "0.6",
        "--issued-at", ISSUED_AT, "--commit", COMMIT, "--out-dir", str(out_dir),
    ]
    for name in FIXED_FILES:
        bad_argv.extend(("--fixed-file", name))
    assert sbom.main(bad_argv) == 1


