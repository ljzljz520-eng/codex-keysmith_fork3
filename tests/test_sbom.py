def test_output_files_are_owner_readable(tmp_path):
    repo = make_repo(tmp_path / "repo")
    spdx_document, cdx_document, _ = build(repo)
    out_dir = tmp_path / "out"
    sbom.write_sbom_documents(spdx_document, cdx_document, out_dir=out_dir, tag="v0.6.0")
