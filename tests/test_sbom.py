PIP_PINS = "# build toolchain\nPyInstaller==6.16.0\n"


def _write(repo: Path, relative: str, content) -> None:
    path = repo / relative
    path.parent.mkdir(parents=True, exist_ok=True)
    if isinstance(content, bytes):
        path.write_bytes(content)
    else:
        path.write_text(content, encoding="utf-8")


def make_repo(repo: Path, *, with_desktop: bool = True, npm_lock=None,
              cargo_lock=CARGO_LOCK, pip_pins=PIP_PINS) -> Path:
    for name in FIXED_FILES:
        _write(repo, name, "content of {}\n".format(name))
    _write(repo, "scenarios/example_fixture/scenario.json",
           '{"schema_version": 1, "id": "example_fixture"}\n')
    _write(repo, "scenarios/example_fixture/task.md", "# task\n")
    _write(repo, "fixture_packs/demo_pack/README.md", "# demo pack\n")
    if with_desktop:
        _write(repo, "gui/package-lock.json",
               json.dumps(npm_lock if npm_lock is not None else NPM_LOCK, indent=2,
                          sort_keys=True))
        _write(repo, "gui/src-tauri/Cargo.lock", cargo_lock)
        _write(repo, "gui/requirements-build.txt", pip_pins)
    return repo


def build(repo, **overrides):
    kwargs = dict(
        repo_root=repo,
        release_line="stable",
        version="0.6.0",
        issued_at=ISSUED_AT,
        source_commit=COMMIT,
        builder={"workflow_name": "release.yml", "runner": "ubuntu-24.04"},
        fixed_files=FIXED_FILES,
    )
    kwargs.update(overrides)
    return sbom.build_documents(**kwargs)


def cdx_libraries(cdx_document):
    return [c for c in cdx_document["components"] if c["type"] == "library"]


def cdx_files(cdx_document):
    return [c for c in cdx_document["components"] if c["type"] == "file"]


def find_library(cdx_document, fragment, *, version=None):
    hits = [
        component for component in cdx_libraries(cdx_document)
        if fragment in component.get("purl", component.get("name", ""))
        and (version is None or component["version"] == version)
    ]
    assert len(hits) == 1, "expected exactly one {!r}, got {}".format(fragment, hits)
    return hits[0]


